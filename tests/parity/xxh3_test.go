func xxh3Mix16(in, secret []byte) uint64 {
	hi, lo := bits.Mul64(binary.LittleEndian.Uint64(in)^binary.LittleEndian.Uint64(secret),
		binary.LittleEndian.Uint64(in[8:])^binary.LittleEndian.Uint64(secret[8:]))
	return hi ^ lo
}

func xxh3Avalanche(h uint64) uint64 {
	h ^= h >> 37
	h *= 0x165667919E3779F9
	return h ^ h>>32
}

// xxh3_64 is `XXH3_64bits()` (seed 0, the default secret) for inputs of 129 to 240 bytes, the only lengths the
// harness hashes (a bearer token's 136-byte signature input): `XXH3_len_129to240_64b()`.
func xxh3_64(in []byte) uint64 {
	if len(in) < 129 || len(in) > 240 {
		panic("xxh3_64: only 129 to 240 bytes")
	}
	acc := uint64(len(in)) * 0x9E3779B185EBCA87
	for i := range 8 {
		acc += xxh3Mix16(in[16*i:], xxh3Secret[16*i:])
	}
	acc = xxh3Avalanche(acc)
	for i := 8; i < len(in)/16; i++ {
		acc += xxh3Mix16(in[16*i:], xxh3Secret[16*(i-8)+3:])
	}
	acc += xxh3Mix16(in[len(in)-16:], xxh3Secret[119:])
	return xxh3Avalanche(acc)
}

// TestXXH3 checks the port against twox-hash 2.1.2's vectors (`xxhash3_64.rs` `test_129_to_240_bytes`: bytes i%251).
func TestXXH3(t *testing.T) {
	for n, want := range map[int]uint64{129: 0xec7642b431ba3e5a, 130: 0x4d3224b100908a87, 131: 0xe57f7ea6741fe3a0,
		238: 0x30449a0b4899dee9, 239: 0x972b14e3c46f214b, 240: 0x375a384d957fe865} {
		in := make([]byte, n)
		for i := range in {
			in[i] = byte(i % 251)
		}
		if got := xxh3_64(in); got != want {
			t.Errorf("%d bytes: %#x, want %#x", n, got, want)
		}
	}
}
