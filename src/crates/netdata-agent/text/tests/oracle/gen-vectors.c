// 1. number printing

// keeps the compiler from folding the conversions of non-finite constants
static double opaque(double v) {
    volatile double x = v;
    return x;
}

// the bit patterns already written, so that every input appears once
#define SEEN_SLOTS (1 << 17)
static uint64_t seen_bits[SEEN_SLOTS];
static bool seen_used[SEEN_SLOTS];

static bool seen_before(uint64_t bits) {
    size_t slot = (size_t)((bits * 0x9e3779b97f4a7c15ULL) >> 47);
    while(seen_used[slot]) {
        if(seen_bits[slot] == bits)
            return true;
        slot = (slot + 1) & (SEEN_SLOTS - 1);
    }
    seen_used[slot] = true;
    seen_bits[slot] = bits;
    return false;
}

static void print_double_line(FILE *f, BUFFER *wb, double value) {
    char tmp[DOUBLE_MAX_LENGTH + 2];
    double v = opaque(value);
    if(seen_before(bits_of(v)))
        return;

    fprintf(f, "%016" PRIx64, bits_of(v));

    print_netdata_double(tmp, v);
    tab(f); esc_str(f, tmp);

    buffer_flush(wb);
    buffer_print_netdata_double_encoded(wb, NUMBER_ENCODING_DECIMAL, v);
    tab(f); esc_str(f, buffer_tostring(wb));

    buffer_flush(wb);
    buffer_print_netdata_double_encoded(wb, NUMBER_ENCODING_HEX, v);
    tab(f); esc_str(f, buffer_tostring(wb));

    buffer_flush(wb);
    buffer_print_netdata_double_encoded(wb, NUMBER_ENCODING_BASE64, v);
    tab(f); esc_str(f, buffer_tostring(wb));

    eol(f);
}

static void gen_print_double(const char *dir, BUFFER *wb) {
    FILE *f = out_open(dir, "print_double.tsv",
                       "f64 bits (hex) | print_netdata_double | buffer_print_netdata_double | hex encoded | base64 encoded");

    const uint64_t special_bits[] = {
        0x0000000000000000ULL, 0x8000000000000000ULL, 0x7ff0000000000000ULL, 0xfff0000000000000ULL,
        0x7ff8000000000000ULL, 0xfff8000000000000ULL, 0x7ff0000000000001ULL, 0x7ff4000000000000ULL,
        0xfff8000000000123ULL, 0x0000000000000001ULL, 0x8000000000000001ULL, 0x000fffffffffffffULL,
        0x0010000000000000ULL, 0x7fefffffffffffffULL, 0xffefffffffffffffULL,
    };
    for(size_t i = 0; i < COUNT(special_bits); i++)
        print_double_line(f, wb, double_of(special_bits[i]));

    // the unit test tables of daemon/unit_test.c and storage_number/tests
    const double table[] = {
        0, 0.0000001, 0.00000009, 0.000000001, 99.99999999999999999, -99.99999999999999999,
        123.4567899123456789, 123.4567890123456789, 123.4567800123456789, 123.4567000123456789,
        123.4560000123456789, 123.4500000123456789, 123.4000000123456789, 123.0000000123456789,
        123.0000000923456789, 4294967295.123456789, 8294967295.123456789, 1.000000000000002e+19,
        9.2233720368547676e+18, 18446744073709541376.0, 18446744073709551616.0, 12318446744073710600192.0,
        1677721499999999885312.0, -1677721499999999885312.0, -1.677721499999999885312e40,
        -16777214999999997337621690403742592008192.0, 9999.9999999, -9999.9999999, 1.5, 1.23e+14,
        9.12345678901234567890123456789e+45, 16.777218, 0.5, 0.05, 0.00000005, 0.00000015, 0.00000025,
        -0.00000004, -0.00000005, -0.00000006, 1e-300, -1e-300,
    };
    for(size_t i = 0; i < COUNT(table); i++)
        print_double_line(f, wb, table[i]);

    // the switch to exponential notation and its neighbourhood
    double threshold = (double)(UINT64_MAX / 10);
    for(int sign = 0; sign < 2; sign++) {
        double v = sign ? -threshold : threshold;
        double lo = v, hi = v;
        print_double_line(f, wb, v);
        for(int i = 0; i < 64; i++) {
            lo = nextafter(lo, 0);
            hi = nextafter(hi, sign ? -INFINITY : INFINITY);
            print_double_line(f, wb, lo);
            print_double_line(f, wb, hi);
        }
    }

    // powers of ten and their neighbours
    for(int e = -330; e <= 310; e++) {
        double p = pow(10, e);
        const double mul[] = { 1, 2, 5, 9.999999, 0.999999999 };
        for(size_t m = 0; m < COUNT(mul); m++) {
            double v = p * mul[m];
            print_double_line(f, wb, v);
            print_double_line(f, wb, -v);
            print_double_line(f, wb, nextafter(v, INFINITY));
            print_double_line(f, wb, nextafter(v, 0));
        }
    }

    // exact binary fractions (ties in llrint) and 7-digit rounding edges
    for(int k = 1; k <= 30; k++) {
        for(int n = 1; n < 64; n += 2) {
            double v = (double)n / (double)(1ULL << k);
            print_double_line(f, wb, v);
            print_double_line(f, wb, -v);
            print_double_line(f, wb, v + 1000.0);
        }
    }
    for(int i = 0; i < 2000; i++) {
        double base = (double)rnd_below(100000);
        double v = base + (double)rnd_below(10000000) / 1e7 + (double)((int)rnd_below(21) - 10) * 1e-9;
        print_double_line(f, wb, v);
    }

    // integers around 2^53, 2^63 and 2^64
    for(int e = 50; e <= 66; e++) {
        double p = ldexp(1, e);
        for(int d = -4; d <= 4; d++) {
            print_double_line(f, wb, p + d);
            print_double_line(f, wb, nextafter(p, d < 0 ? 0 : INFINITY));
        }
    }

    for(int i = 0; i < 12000; i++)
        print_double_line(f, wb, rnd_double());

    fclose(f);
}

static void gen_print_integers(const char *dir, BUFFER *wb) {
    FILE *fu = out_open(dir, "print_uint64.tsv", "u64 | decimal | hex | hex full | base64");
    FILE *fi = out_open(dir, "print_int64.tsv", "i64 | decimal | hex | base64");

    uint64_t values[8000];
    size_t n = 0;
    values[n++] = 0;
    values[n++] = UINT64_MAX;
    values[n++] = (uint64_t)INT64_MAX;
    values[n++] = (uint64_t)INT64_MIN;
    values[n++] = 1676071986;
    for(int b = 0; b < 64; b++) {
        values[n++] = 1ULL << b;
        values[n++] = (1ULL << b) - 1;
        values[n++] = (1ULL << b) + 1;
        values[n++] = 0 - (1ULL << b);
    }
    for(uint64_t p = 1, i = 0; i < 20; i++, p *= 10) {
        values[n++] = p;
        values[n++] = p - 1;
        values[n++] = p + 1;
    }
    while(n < COUNT(values))
        values[n++] = rnd() >> rnd_below(64);

    for(size_t i = 0; i < n; i++) {
        uint64_t v = values[i];

        fprintf(fu, "%" PRIu64, v);
        buffer_flush(wb); buffer_print_uint64_encoded(wb, NUMBER_ENCODING_DECIMAL, v);
        tab(fu); esc_str(fu, buffer_tostring(wb));
        buffer_flush(wb); buffer_print_uint64_encoded(wb, NUMBER_ENCODING_HEX, v);
        tab(fu); esc_str(fu, buffer_tostring(wb));
        buffer_flush(wb); buffer_print_uint64_hex_full(wb, v);
        tab(fu); esc_str(fu, buffer_tostring(wb));
        buffer_flush(wb); buffer_print_uint64_encoded(wb, NUMBER_ENCODING_BASE64, v);
        tab(fu); esc_str(fu, buffer_tostring(wb));
        eol(fu);

        int64_t s = (int64_t)v;
        fprintf(fi, "%" PRId64, s);
        buffer_flush(wb); buffer_print_int64_encoded(wb, NUMBER_ENCODING_DECIMAL, s);
        tab(fi); esc_str(fi, buffer_tostring(wb));
        buffer_flush(wb); buffer_print_int64_encoded(wb, NUMBER_ENCODING_HEX, s);
        tab(fi); esc_str(fi, buffer_tostring(wb));
        buffer_flush(wb); buffer_print_int64_encoded(wb, NUMBER_ENCODING_BASE64, s);
        tab(fi); esc_str(fi, buffer_tostring(wb));
        eol(fi);
    }

    fclose(fu);
    fclose(fi);
}

