// 2. number parsing

static void parse_line(FILE *f, const char *input) {
    char *end;
    esc_str(f, input);

    NETDATA_DOUBLE d = str2ndd(input, &end);
    fprintf(f, "\t%016" PRIx64 "\t%td", bits_of(d), end - input);

    d = str2ndd_encoded(input, &end);
    fprintf(f, "\t%016" PRIx64 "\t%td", bits_of(d), end - input);

    d = strtod(input, &end);
    fprintf(f, "\t%016" PRIx64 "\t%td", bits_of(d), end - input);

    uint64_t u64 = str2uint64_t(input, &end);
    fprintf(f, "\t%" PRIu64 "\t%td", u64, end - input);

    uint32_t u32 = str2uint32_t(input, &end);
    fprintf(f, "\t%" PRIu32 "\t%td", u32, end - input);

    long long ll = str2ll(input, &end);
    fprintf(f, "\t%lld\t%td", ll, end - input);

    fprintf(f, "\t%u\t%d\t%lu\t%ld", str2u(input), str2i(input), str2ul(input), str2l(input));
    fprintf(f, "\t%llu\t%lld", str2ull_encoded(input), str2ll_encoded(input));

    u64 = str2uint64_hex(input, &end);
    fprintf(f, "\t%" PRIu64 "\t%td", u64, end - input);

    u32 = str2uint32_hex(input, &end);
    fprintf(f, "\t%" PRIu32 "\t%td", u32, end - input);

    u64 = str2uint64_base64(input, &end);
    fprintf(f, "\t%" PRIu64 "\t%td", u64, end - input);

    eol(f);
}

