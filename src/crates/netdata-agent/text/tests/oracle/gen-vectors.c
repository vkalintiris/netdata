static void sp_case(FILE *fm, FILE *fi, const char *pattern, const sp_separators *seps, SIMPLE_PREFIX_MODE mode,
                    bool cs, const char *const *strings, size_t count) {
    SIMPLE_PATTERN *p = simple_pattern_create(pattern, seps->separators, mode, cs);

    sp_head(fi, pattern, seps, mode, cs);
    fprintf(fi, "\t%d\t%d\t", simple_pattern_contains_wildcards(pattern, seps->separators),
            p ? simple_pattern_is_potential_name(p) : 0);
    {
        SIMPLE_PATTERN *it = p;
        bool first = true;
        while(it) {
            char *m = simple_pattern_iterate(&it);
            if(!first) fputs("\\x1f", fi);
            first = false;
            if(m) { fputc('+', fi); esc_str(fi, m); }
            else fputc('-', fi);
        }
    }
    eol(fi);

    for(size_t i = 0; i < count; i++) {
        const char *s = strings[i];
        const size_t sizes[] = { 0, 1, 2, 4, 1024 };
        size_t wsize = sizes[rnd_below(COUNT(sizes))];
        char wildcarded[1024];
        wildcarded[0] = '\0';
        SIMPLE_PATTERN_RESULT r = simple_pattern_matches_extract(p, s, wsize ? wildcarded : NULL, wsize);

        sp_head(fm, pattern, seps, mode, cs);
        tab(fm); esc_str(fm, s);
        fprintf(fm, "\t%zu\t%d\t", wsize, (int)r);
        esc_str(fm, wildcarded);
        eol(fm);
    }

    simple_pattern_free(p);
}

