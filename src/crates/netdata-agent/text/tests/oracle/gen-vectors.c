// Golden vector generator for the netdata-agent-text crate.
//
// Links against the production libnetdata (see gen-vectors.sh) and writes one
// tab-separated file per function family into the directory given as the
// only argument. Inputs are deterministic (fixed-seed splitmix64).
//
// Field encoding (shared with tests/common/mod.rs): bytes 0x20..0x7e except
// '\' and '#' are written as-is, '\' as "\\", every other byte as "\xHH".
// Lines that start with '#' are comments (data never starts with a raw '#').
// Multi-valued fields join items with 0x1f before encoding.

#include "libnetdata/libnetdata.h"

// ------------------------------------------------------------------------------------------------
// output helpers

static FILE *out_open(const char *dir, const char *name, const char *columns) {
    char path[4096];
    snprintf(path, sizeof(path), "%s/%s", dir, name);
    FILE *f = fopen(path, "w");
    if(!f) {
        fprintf(stderr, "cannot create %s\n", path);
        exit(1);
    }
    fprintf(f, "# generated by tests/oracle/gen-vectors.c from the C implementation; do not edit\n");
    fprintf(f, "# columns: %s\n", columns);
    return f;
}

static void esc(FILE *f, const void *data, size_t len) {
    const unsigned char *s = data;
    for(size_t i = 0; i < len; i++) {
        unsigned char c = s[i];
        if(c == '\\')
            fputs("\\\\", f);
        else if(c >= 0x20 && c <= 0x7e && c != '#')
            fputc(c, f);
        else
            fprintf(f, "\\x%02x", c);
    }
}

static void esc_str(FILE *f, const char *s) {
    esc(f, s, strlen(s));
}

static void tab(FILE *f) { fputc('\t', f); }
static void eol(FILE *f) { fputc('\n', f); }

static uint64_t bits_of(double d) {
    uint64_t u;
    memcpy(&u, &d, sizeof(u));
    return u;
}

static double double_of(uint64_t u) {
    double d;
    memcpy(&d, &u, sizeof(d));
    return d;
}

// ------------------------------------------------------------------------------------------------
// deterministic randomness

static uint64_t rng_state = 0x6e65746461746121ULL;

static uint64_t rnd(void) {
    uint64_t z = (rng_state += 0x9e3779b97f4a7c15ULL);
    z = (z ^ (z >> 30)) * 0xbf58476d1ce4e5b9ULL;
    z = (z ^ (z >> 27)) * 0x94d049bb133111ebULL;
    return z ^ (z >> 31);
}

static uint64_t rnd_below(uint64_t n) {
    return n ? rnd() % n : 0;
}

static const char *pick(const char *const *items, size_t count) {
    return items[rnd_below(count)];
}

#define PICK(arr) pick((arr), sizeof(arr) / sizeof((arr)[0]))
#define COUNT(arr) (sizeof(arr) / sizeof((arr)[0]))

// a random string of up to max_len bytes drawn from alphabet
static void rnd_string(char *dst, size_t max_len, const char *alphabet) {
    size_t n = rnd_below(max_len + 1);
    size_t a = strlen(alphabet);
    for(size_t i = 0; i < n; i++)
        dst[i] = alphabet[rnd_below(a)];
    dst[n] = '\0';
}

// a random string made of tokens
static void rnd_tokens(char *dst, size_t dst_size, const char *const *tokens, size_t count, size_t max_tokens) {
    dst[0] = '\0';
    size_t n = rnd_below(max_tokens + 1);
    for(size_t i = 0; i < n; i++) {
        const char *t = tokens[rnd_below(count)];
        if(strlen(dst) + strlen(t) + 1 >= dst_size)
            break;
        strcat(dst, t);
    }
}

// random double: raw bits, "decimal-like" or scaled integers
static double rnd_double(void) {
    switch(rnd_below(6)) {
        case 0:
            return double_of(rnd());
        case 1: {
            double v = (double)rnd_below(100000000) / pow(10, (double)rnd_below(12));
            return rnd_below(2) ? -v : v;
        }
        case 2: {
            double v = (double)(rnd() >> rnd_below(64));
            return rnd_below(2) ? -v : v;
        }
        case 3: {
            // exact binary fractions: llrint() ties
            double v = (double)rnd_below(1 << 20) / (double)(1ULL << rnd_below(40));
            return rnd_below(2) ? -v : v;
        }
        case 4: {
            double v = pow(10, (double)((int)rnd_below(640) - 320)) * (1.0 + (double)rnd_below(1000) / 1000.0);
            return rnd_below(2) ? -v : v;
        }
        default: {
            double v = (double)rnd_below(1000000) + (double)rnd_below(10000000) * 1e-7 + ((double)rnd_below(3) - 1.0) * 5e-8;
            return rnd_below(2) ? -v : v;
        }
    }
}

