static void gen_json_escape(const char *dir) {
    FILE *f = out_open(dir, "json_escape.tsv", "input | buffer_json_strcat | buffer_json_quoted_strcat");
    BUFFER *wb = buffer_create(0, NULL);

    unsigned char input[64];
    for(int i = 0; i < 4000; i++) {
        size_t len;
        if(i < 255) {
            input[0] = (unsigned char)(i + 1);
            len = 1;
        }
        else {
            len = rnd_below(12);
            for(size_t k = 0; k < len; k++)
                input[k] = rnd_below(3) ? (unsigned char)"\"\\\n\r\t\b\f\x01\x1f\x7f\xc3\xa9" "ab/'"[rnd_below(17)]
                                        : (unsigned char)(1 + rnd_below(255));
        }
        input[len] = '\0';

        esc(f, input, len); tab(f);
        buffer_flush(wb); buffer_json_strcat(wb, (const char *)input);
        esc_str(f, buffer_tostring(wb)); tab(f);
        buffer_flush(wb); buffer_json_quoted_strcat(wb, (const char *)input);
        esc_str(f, buffer_tostring(wb)); eol(f);
    }

    buffer_free(wb);
    fclose(f);
}

// Scripts: operations joined with 0x1e, arguments with 0x1f (both encoded as \x1e / \x1f);
// arguments are hex encoded so that they never contain the separators.
// The first operation is always the initialization: I <key quote> <value quote> <depth> <anonymous> <options>.

typedef struct {
    FILE *f;
    bool first;
} script;

static void op_begin(script *s, const char *code) {
    if(!s->first) fputs("\\x1e", s->f);
    s->first = false;
    esc_str(s->f, code);
}

static void op_arg(script *s, const void *data, size_t len) {
    fputs("\\x1f", s->f);
    for(size_t i = 0; i < len; i++)
        fprintf(s->f, "%02x", ((const unsigned char *)data)[i]);
}

static void op_arg_str(script *s, const char *str) {
    op_arg(s, str, strlen(str));
}

static void op_arg_u64(script *s, uint64_t v) {
    char tmp[32];
    snprintf(tmp, sizeof(tmp), "%" PRIu64, v);
    op_arg_str(s, tmp);
}

static void op_arg_i64(script *s, int64_t v) {
    char tmp[32];
    snprintf(tmp, sizeof(tmp), "%" PRId64, v);
    op_arg_str(s, tmp);
}

static const char *json_strings[] = {
    "", "a", "hello", "world", "with space", "quote\"inside", "back\\slash", "tab\there", "new\nline",
    "\r\b\f", "\x01\x02\x1f", "\x7f", "caf\xc3\xa9", "\xf0\x9f\x98\x80", "\xff\xfe", "\"quoted\"", "\"", "\"\"",
    "null", "NULL", "/slash/", "'single'", "a\"b\"", "\"lead", "trail\"", "{}", "[]", ",:", "0", "-1.5",
};

static void rnd_uuid(unsigned char *uuid) {
    if(rnd_below(4) == 0) {
        memset(uuid, 0, 16);
        return;
    }
    for(int i = 0; i < 16; i++)
        uuid[i] = (unsigned char)rnd();
}

static void json_script(FILE *f, BUFFER *wb) {
    script s = { .f = f, .first = true };

    static const char *quotes[] = { "\"", "\"", "\"", "", "'", "``", "12345678" };
    const char *kq = PICK(quotes);
    const char *vq = rnd_below(3) ? kq : PICK(quotes);
    static const BUFFER_JSON_OPTIONS options[] = {
        BUFFER_JSON_OPTIONS_DEFAULT, BUFFER_JSON_OPTIONS_MINIFY, BUFFER_JSON_OPTIONS_NEWLINE_ON_ARRAY_ITEMS,
        BUFFER_JSON_OPTIONS_MINIFY | BUFFER_JSON_OPTIONS_NEWLINE_ON_ARRAY_ITEMS,
    };
    BUFFER_JSON_OPTIONS opt = options[rnd_below(COUNT(options))];
    bool anonymous = rnd_below(5) != 0;
    int depth = rnd_below(6) == 0 ? (int)(1 + rnd_below(3)) : 0;
    bool finalize = depth == 0 && rnd_below(8) != 0;

    buffer_flush(wb);
    buffer_json_initialize(wb, kq, vq, depth, anonymous, opt);
    op_begin(&s, "I");
    op_arg_str(&s, kq);
    op_arg_str(&s, vq);
    op_arg_i64(&s, depth);
    op_arg_u64(&s, anonymous);
    op_arg_u64(&s, opt);

    // what is open above the root: 'o' object, 'a' array
    char open[BUFFER_JSON_MAX_DEPTH];
    int level = 0;
    size_t ops = rnd_below(40);
    int in_array = 0;

    for(size_t i = 0; i < ops; i++) {
        in_array = level > 0 && open[level - 1] == 'a';
        const char *key = PICK(json_strings);
        const char *value = PICK(json_strings);
        unsigned char uuid[16];
        uint64_t u = rnd() >> rnd_below(64);
        double d = rnd_below(8) == 0 ? (rnd_below(2) ? NAN : INFINITY) : rnd_double();
        int64_t t = rnd_below(3) == 0 ? 0 : (int64_t)(rnd() >> (1 + rnd_below(63)));
        if(rnd_below(5) == 0) t = -t;

        // prefer items inside arrays and members inside objects, but mix
        unsigned what = (unsigned)rnd_below(100);
        bool items = in_array ? what < 85 : what < 10;
        unsigned k = (unsigned)rnd_below(items ? 16 : 22);

        if(level > 0 && rnd_below(6) == 0) {
            if(open[level - 1] == 'o') { buffer_json_object_close(wb); op_begin(&s, "OC"); }
            else { buffer_json_array_close(wb); op_begin(&s, "AC"); }
            level--;
            continue;
        }

        if(items) {
            switch(k) {
                case 0: if(level + depth < 28) { buffer_json_add_array_item_array(wb); op_begin(&s, "IA"); open[level++] = 'a'; } break;
                case 1: if(level + depth < 28) { buffer_json_add_array_item_object(wb); op_begin(&s, "IO"); open[level++] = 'o'; } break;
                case 2: buffer_json_add_array_item_string(wb, value); op_begin(&s, "IS"); op_arg_str(&s, value); break;
                case 3: buffer_json_add_array_item_string(wb, NULL); op_begin(&s, "IN"); break;
                case 4: rnd_uuid(uuid); buffer_json_add_array_item_uuid(wb, (nd_uuid_t *)uuid); op_begin(&s, "IU"); op_arg(&s, uuid, 16); break;
                case 5: rnd_uuid(uuid); buffer_json_add_array_item_uuid_compact(wb, (nd_uuid_t *)uuid); op_begin(&s, "IUC"); op_arg(&s, uuid, 16); break;
                case 6: buffer_json_add_array_item_double(wb, d); op_begin(&s, "ID"); op_arg_u64(&s, bits_of(d)); break;
                case 7: buffer_json_add_array_item_int64(wb, (int64_t)u); op_begin(&s, "II"); op_arg_i64(&s, (int64_t)u); break;
                case 8: buffer_json_add_array_item_uint64(wb, u); op_begin(&s, "IU64"); op_arg_u64(&s, u); break;
                case 9: buffer_json_add_array_item_boolean(wb, u & 1); op_begin(&s, "IB"); op_arg_u64(&s, u & 1); break;
                case 10: buffer_json_add_array_item_time_t(wb, t); op_begin(&s, "IT"); op_arg_i64(&s, t); break;
                case 11: buffer_json_add_array_item_time_ms(wb, t); op_begin(&s, "ITM"); op_arg_i64(&s, t); break;
                case 12: buffer_json_add_array_item_time_t_formatted(wb, t, u & 1); op_begin(&s, "ITF"); op_arg_i64(&s, t); op_arg_u64(&s, u & 1); break;
                case 13: buffer_json_add_array_item_datetime_rfc3339(wb, u, true); op_begin(&s, "IDT"); op_arg_u64(&s, u); break;
                case 14: buffer_json_add_array_item_uuid(wb, NULL); op_begin(&s, "IUN"); break;
                default: buffer_fast_strcat(wb, value, strlen(value)); op_begin(&s, "R"); op_arg_str(&s, value); break;
            }
        }
        else {
            switch(k) {
                case 0: if(level + depth < 28) { buffer_json_member_add_object(wb, key); op_begin(&s, "MO"); op_arg_str(&s, key); open[level++] = 'o'; } break;
                case 1: if(level + depth < 28) { buffer_json_member_add_array(wb, key); op_begin(&s, "MA"); op_arg_str(&s, key); open[level++] = 'a'; } break;
                case 2: if(level + depth < 28) { buffer_json_member_add_array(wb, NULL); op_begin(&s, "MAN"); open[level++] = 'a'; } break;
                case 3: buffer_json_member_add_string(wb, key, value); op_begin(&s, "MS"); op_arg_str(&s, key); op_arg_str(&s, value); break;
                case 4: buffer_json_member_add_string(wb, key, NULL); op_begin(&s, "MN"); op_arg_str(&s, key); break;
                case 5: buffer_json_member_add_string_or_omit(wb, key, value); op_begin(&s, "MSO"); op_arg_str(&s, key); op_arg_str(&s, value); break;
                case 6:
                    if(rnd_below(2)) { buffer_json_member_add_string_or_empty(wb, key, value); op_begin(&s, "MSE"); op_arg_str(&s, key); op_arg_str(&s, value); }
                    else { buffer_json_member_add_string_or_empty(wb, key, NULL); op_begin(&s, "MSEN"); op_arg_str(&s, key); }
                    break;
                case 7: buffer_json_member_add_quoted_string(wb, key, value); op_begin(&s, "MQ"); op_arg_str(&s, key); op_arg_str(&s, value); break;
                case 8: rnd_uuid(uuid); buffer_json_member_add_uuid(wb, key, *(nd_uuid_t *)uuid); op_begin(&s, "MU"); op_arg_str(&s, key); op_arg(&s, uuid, 16); break;
                case 9: rnd_uuid(uuid); buffer_json_member_add_uuid_ptr(wb, key, (nd_uuid_t *)uuid); op_begin(&s, "MUP"); op_arg_str(&s, key); op_arg(&s, uuid, 16); break;
                case 10: rnd_uuid(uuid); buffer_json_member_add_uuid_compact(wb, key, *(nd_uuid_t *)uuid); op_begin(&s, "MUC"); op_arg_str(&s, key); op_arg(&s, uuid, 16); break;
                case 11: buffer_json_member_add_boolean(wb, key, u & 1); op_begin(&s, "MB"); op_arg_str(&s, key); op_arg_u64(&s, u & 1); break;
                case 12: buffer_json_member_add_uint64(wb, key, u); op_begin(&s, "MU64"); op_arg_str(&s, key); op_arg_u64(&s, u); break;
                case 13: buffer_json_member_add_int64(wb, key, (int64_t)u); op_begin(&s, "MI"); op_arg_str(&s, key); op_arg_i64(&s, (int64_t)u); break;
                case 14: buffer_json_member_add_double(wb, key, d); op_begin(&s, "MD"); op_arg_str(&s, key); op_arg_u64(&s, bits_of(d)); break;
                case 15: buffer_json_member_add_time_t(wb, key, t); op_begin(&s, "MT"); op_arg_str(&s, key); op_arg_i64(&s, t); break;
                case 16: buffer_json_member_add_time_t_formatted(wb, key, t, u & 1); op_begin(&s, "MTF"); op_arg_str(&s, key); op_arg_i64(&s, t); op_arg_u64(&s, u & 1); break;
                case 17: buffer_json_member_add_datetime_rfc3339(wb, key, u, true); op_begin(&s, "MDT"); op_arg_str(&s, key); op_arg_u64(&s, u); break;
                case 18: {
                    int64_t duration = (int64_t)(u >> 1) * (rnd_below(2) ? 1 : -1);
                    buffer_json_member_add_duration_ut(wb, key, duration); op_begin(&s, "MDU"); op_arg_str(&s, key); op_arg_i64(&s, duration);
                    break;
                }
                case 19: buffer_json_member_add_uuid_ptr(wb, key, NULL); op_begin(&s, "MUPN"); op_arg_str(&s, key); break;
                case 20: buffer_json_member_add_quoted_string(wb, key, NULL); op_begin(&s, "MQN"); op_arg_str(&s, key); break;
                default: buffer_json_member_add_string_or_omit(wb, key, NULL); op_begin(&s, "MSON"); op_arg_str(&s, key); break;
            }
        }
    }

    if(finalize) {
        buffer_json_finalize(wb);
        op_begin(&s, "F");
    }

    tab(f);
    esc(f, buffer_tostring(wb), buffer_strlen(wb));
    eol(f);
}

static void gen_json(const char *dir) {
    FILE *f = out_open(dir, "json.tsv", "operations script | output");
    BUFFER *wb = buffer_create(0, NULL);
    for(int i = 0; i < 1500; i++)
        json_script(f, wb);
    buffer_free(wb);
    fclose(f);

    f = out_open(dir, "rfc3339.tsv", "usec | fractional digits | rfc3339_datetime_ut(utc)");
    for(int i = 0; i < 3000; i++) {
        uint64_t ut;
        switch(rnd_below(4)) {
            case 0: ut = rnd(); break;
            case 1: ut = rnd_below(4102444800ULL) * 1000000ULL; break;
            case 2: ut = rnd_below(4102444800ULL) * 1000000ULL + rnd_below(1000000); break;
            default: ut = rnd_below(253402300800ULL * 1000000ULL); break;
        }
        if(i < 4) ut = (uint64_t[]){ 0, 1, 999999, 951782400000000ULL }[i];
        size_t digits = rnd_below(12);
        char buf[RFC3339_MAX_LENGTH];
        rfc3339_datetime_ut(buf, sizeof(buf), ut, digits, true);
        fprintf(f, "%" PRIu64 "\t%zu\t", ut, digits);
        esc_str(f, buf);
        eol(f);
    }
    fclose(f);
}

