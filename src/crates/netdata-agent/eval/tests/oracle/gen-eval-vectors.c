// spell: every spelling and letter case of each operator and keyword, with and without spaces

static void spell_word(const char *word, const char *const *templates, size_t count) {
    SB b = { 0 };
    size_t n = strlen(word);
    char variant[16];
    for(unsigned mask = 0; mask < (1u << n); mask++) {
        for(size_t i = 0; i < n; i++)
            variant[i] = (char)(((mask >> i) & 1) ? toupper((unsigned char)word[i]) : word[i]);
        variant[n] = '\0';
        for(size_t t = 0; t < count; t++)
            corpus_row("spell", subst(&b, templates[t], variant));
    }
    freez(b.s);
}

