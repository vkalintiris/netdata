// rand and mut: random valid expressions, and single edits of them

#define MAX_TOKENS 8192
static const char *tokens[MAX_TOKENS];
static size_t tokens_count;

static void token(const char *t) {
    if(tokens_count == MAX_TOKENS) {
        fprintf(stderr, "too many tokens\n");
        exit(1);
    }
    tokens[tokens_count++] = t;
}

static const char *const rand_numbers[] = {
    "0", "1", "2", "3", "7", "10", "0.5", "2.5", "1e3", "1e-3", ".25", "5.", "100", "1e308", "nan", "inf", "NaN", "Inf",
    "null", "infinity", "0.0000001", "1.0000001", "1.00000001",
};
static const char *const rand_variables[] = {
    "$a", "${a}", "$b", "${b}", "$c", "${c}", "$zero", "$neg", "$half", "$big", "$tiny", "$u", "${u}", "$a.b", "${a b}",
};
static const char *const rand_binary[] = {
    "+", "-", "*", "/", "%", "&&", "and", "AND", "||", "or", "OR", "==", "=", "!=", "<>", "<", "<=", ">", ">=",
};
static const char *const rand_unary[] = { "-", "+", "!", "not", "NOT" };
static const char *const rand_abs[] = { "abs", "ABS", "Abs" };
static const char *const rand_junk[] = { "(", ")", "?", ":", "@", "$", "${", "}", "abs", "1", "$a", "+", "!", "and", "=", "." };

static void rand_expr(int depth) {
    switch(depth <= 0 ? rnd_below(2) : rnd_below(10)) {
        case 0:
        case 9:
            token(PICK(rand_numbers));
            break;
        case 1:
            token(PICK(rand_variables));
            break;
        case 2:
        case 3:
        case 4:
            rand_expr(depth - 1);
            token(PICK(rand_binary));
            rand_expr(depth - 1);
            break;
        case 5:
            token(PICK(rand_unary));
            rand_expr(depth - 1);
            break;
        case 6:
            token("(");
            rand_expr(depth - 1);
            token(")");
            break;
        case 7:
            token(PICK(rand_abs));
            token("(");
            rand_expr(depth - 1);
            token(")");
            break;
        default:
            rand_expr(depth - 1);
            token("?");
            rand_expr(depth - 1);
            token(":");
            rand_expr(depth - 1);
            break;
    }
}

// the tokens with a random separator between each two: usually one space, sometimes none or a run of whitespace
static void rand_join(SB *b, bool single_spaces) {
    static const char whitespace[] = " \t\r\n";
    sb_reset(b);
    for(size_t i = 0; i < tokens_count; i++) {
        if(i) {
            uint64_t r = single_spaces ? 0 : rnd_below(10);
            if(r < 6)
                sb_addc(b, ' ');
            else if(r >= 8)
                for(uint64_t n = 1 + rnd_below(3); n; n--)
                    sb_addc(b, whitespace[rnd_below(4)]);
        }
        sb_add(b, tokens[i]);
    }
}

static void family_rand(void) {
    SB b = { 0 };
    for(int i = 0; i < 4000; i++) {
        tokens_count = 0;
        rand_expr(1 + (int)rnd_below(6));
        rand_join(&b, false);
        corpus_row("rand", b.s);
    }
    freez(b.s);
}

static void family_mut(void) {
    SB b = { 0 };
    for(int i = 0; i < 4000; i++) {
        tokens_count = 0;
        rand_expr(1 + (int)rnd_below(5));

        if(rnd_below(2)) {
            // edit a token
            size_t at = rnd_below(tokens_count);
            switch(rnd_below(4)) {
                case 0: // delete
                    memmove(&tokens[at], &tokens[at + 1], (tokens_count - at - 1) * sizeof(tokens[0]));
                    tokens_count--;
                    break;
                case 1: // insert
                    if(tokens_count < MAX_TOKENS) {
                        memmove(&tokens[at + 1], &tokens[at], (tokens_count - at) * sizeof(tokens[0]));
                        tokens[at] = PICK(rand_junk);
                        tokens_count++;
                    }
                    break;
                case 2: // replace
                    tokens[at] = PICK(rand_junk);
                    break;
                default: // swap with the next one
                    if(at + 1 < tokens_count) {
                        const char *t = tokens[at];
                        tokens[at] = tokens[at + 1];
                        tokens[at + 1] = t;
                    }
                    break;
            }
            rand_join(&b, rnd_below(2));
        }
        else {
            // edit a byte
            rand_join(&b, rnd_below(2));
            size_t at = rnd_below(b.len);
            char c = (char)(1 + rnd_below(255));
            switch(rnd_below(4)) {
                case 0: // delete
                    memmove(&b.s[at], &b.s[at + 1], b.len - at);
                    b.len--;
                    break;
                case 1: // insert
                    sb_room(&b, 1);
                    memmove(&b.s[at + 1], &b.s[at], b.len - at + 1);
                    b.s[at] = c;
                    b.len++;
                    break;
                case 2: // replace
                    b.s[at] = c;
                    break;
                default: // swap with the next one
                    if(at + 1 < b.len) {
                        char t = b.s[at];
                        b.s[at] = b.s[at + 1];
                        b.s[at + 1] = t;
                    }
                    break;
            }
        }
        corpus_row("mut", b.s);
    }
    freez(b.s);
}

