// depth: around the parser's fixed stack

static void depth_row(SB *b, const char *open, size_t n, const char *middle, const char *close, size_t closes) {
    sb_reset(b);
    sb_rep(b, open, n);
    sb_add(b, middle);
    sb_rep(b, close, closes);
    corpus_row("depth", b->s);
}

// n openings, then each middle, left open and fully closed; and, for what a stack reset would leave valid, every
// number of closings near the levels opened since one or two resets
static void depth_family(SB *b, const char *open, const char *close, size_t per_level, const size_t *counts, size_t counts_len) {
    static const char *const middles[] = { "1", "1 + 2", "1 1", "$a" };
    size_t levels = 99 / per_level; // the levels a full stack holds

    for(size_t i = 0; i < counts_len; i++) {
        size_t n = counts[i];
        for(size_t m = 0; m < COUNT(middles); m++) {
            depth_row(b, open, n, middles[m], close, 0);
            if(*close)
                depth_row(b, open, n, middles[m], close, n);
        }
        if(!*close)
            continue;

        for(size_t resets = 1; resets <= 2; resets++) {
            for(long d = -2; d <= 2; d++) {
                long left = (long)n - (long)(resets * levels) + d;
                if(left < 1 || (size_t)left >= n)
                    continue;
                depth_row(b, open, n, "1", close, (size_t)left);
                depth_row(b, open, n, "1 + 2", close, (size_t)left);
            }
        }
    }
}

static void family_depth(void) {
    SB b = { 0 };

    static const size_t singles[] = { 97, 98, 99, 100, 101, 150, 198, 199, 200, 250 };
    depth_family(&b, "(", ")", 1, singles, COUNT(singles));
    depth_family(&b, "!", "", 1, singles, COUNT(singles));
    depth_family(&b, "-", "", 1, singles, COUNT(singles));
    depth_family(&b, "not ", "", 1, singles, COUNT(singles));

    static const size_t ternaries[] = { 23, 24, 25, 26, 27, 49, 50, 51 };
    depth_family(&b, "1 ? 2 : ", "", 4, ternaries, COUNT(ternaries));
    depth_family(&b, "0 ? 2 : ", "", 4, ternaries, COUNT(ternaries));

    static const size_t triples[] = { 31, 32, 33, 34, 35, 65, 66, 67 };
    depth_family(&b, "1+(", ")", 3, triples, COUNT(triples));

    static const size_t pairs[] = { 47, 48, 49, 50, 51, 52, 98, 99, 100 };
    depth_family(&b, "abs(", ")", 2, pairs, COUNT(pairs));
    depth_family(&b, "-(", ")", 2, pairs, COUNT(pairs));

    // chains that never grow the stack
    static const char *const chains[] = { "+1", " * 1", " - $a", " && 1", " == 1" };
    for(size_t i = 0; i < COUNT(chains); i++) {
        sb_reset(&b);
        sb_add(&b, "1");
        sb_rep(&b, chains[i], 1500);
        corpus_row("depth", b.s);
    }

    // a deep tree under the limit: right-leaning through parentheses, then closed
    for(size_t n = 30; n <= 32; n++) {
        sb_reset(&b);
        sb_rep(&b, "$a - (", n);
        sb_add(&b, "$b");
        sb_rep(&b, ")", n);
        corpus_row("depth", b.s);
    }

    freez(b.s);
}

