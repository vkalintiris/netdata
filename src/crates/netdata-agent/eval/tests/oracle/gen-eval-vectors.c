// Golden vector generator for the netdata-agent-eval crate.
//
// Links against the production libnetdata (see gen-eval-vectors.sh) and runs C's expression evaluator
// (src/libnetdata/eval/: the re2c lexer, the Lemon parser, eval-evaluate.c, eval-utils.c) over a deterministic
// corpus: fixed lists and a fixed-seed splitmix64. It writes three tab-separated files into the directory given as
// the only argument:
//
//   bindings.tsv  set, name, value bits: the variables of binding sets 1 and 2; every other name is unknown, and
//                 set 0 is an expression with no lookup callback
//   corpus.tsv    family, input, outcome, code, failed_at, source, parsed_as, then for sets 0, 1 and 2 in turn, on
//                 the same expression: return value, error code, result bits, error_msg
//   hardcode.tsv  input, count, name1, bits1, name2, bits2, source, parsed_as, return value, error code, result
//                 bits, error_msg: one or two expression_hardcode_variable() calls, then one evaluation under set 1
//
// Outcomes: E = expression_parse() returned NULL and touched neither *error nor *failed_at, F = NULL with a code
// and a position (the offset of *failed_at in the input), K = parsed. Fields that do not apply hold "-".
//
// Field encoding (netdata-agent-text's, decoded by its tests/common/mod.rs): bytes 0x20..0x7e except '\' and '#'
// are written as-is, '\' as "\\", every other byte as "\xHH". Lines that start with '#' are comments.

#include "libnetdata/libnetdata.h"
#include "libnetdata/eval/eval-internal.h"

#define COUNT(arr) (sizeof(arr) / sizeof((arr)[0]))

// ------------------------------------------------------------------------------------------------
// output helpers

static FILE *out_open(const char *dir, const char *name, const char *columns) {
    char path[4096];
    snprintf(path, sizeof(path), "%s/%s", dir, name);
    FILE *f = fopen(path, "w");
    if(!f) {
        fprintf(stderr, "cannot create %s\n", path);
        exit(1);
    }
    fprintf(f, "# generated by tests/oracle/gen-eval-vectors.c from the C implementation; do not edit\n");
    fprintf(f, "# columns: %s\n", columns);
    return f;
}

static void esc(FILE *f, const void *data, size_t len) {
    const unsigned char *s = data;
    for(size_t i = 0; i < len; i++) {
        unsigned char c = s[i];
        if(c == '\\')
            fputs("\\\\", f);
        else if(c >= 0x20 && c <= 0x7e && c != '#')
            fputc(c, f);
        else
            fprintf(f, "\\x%02x", c);
    }
}

static void esc_str(FILE *f, const char *s) {
    esc(f, s, strlen(s));
}

static uint64_t bits_of(double d) {
    uint64_t u;
    memcpy(&u, &d, sizeof(u));
    return u;
}

static double double_of(uint64_t u) {
    double d;
    memcpy(&d, &u, sizeof(d));
    return d;
}

// ------------------------------------------------------------------------------------------------
// a growable C string

typedef struct {
    char *s;
    size_t len;
    size_t size;
} SB;

static void sb_room(SB *b, size_t extra) {
    if(b->len + extra + 1 > b->size) {
        b->size = (b->len + extra + 1) * 2;
        b->s = reallocz(b->s, b->size);
    }
}

static void sb_reset(SB *b) {
    sb_room(b, 0);
    b->len = 0;
    b->s[0] = '\0';
}

static void sb_addn(SB *b, const char *s, size_t n) {
    sb_room(b, n);
    memcpy(b->s + b->len, s, n);
    b->len += n;
    b->s[b->len] = '\0';
}

static void sb_add(SB *b, const char *s) {
    sb_addn(b, s, strlen(s));
}

static void sb_addc(SB *b, char c) {
    sb_addn(b, &c, 1);
}

static void sb_rep(SB *b, const char *s, size_t times) {
    for(size_t i = 0; i < times; i++)
        sb_add(b, s);
}

// template with every '@' replaced by value ('%' is an operator here, so no printf formats)
static const char *subst(SB *b, const char *template, const char *value) {
    sb_reset(b);
    for(const char *p = template; *p; p++) {
        if(*p == '@')
            sb_add(b, value);
        else
            sb_addc(b, *p);
    }
    return b->s;
}

// ------------------------------------------------------------------------------------------------
// deterministic randomness

static uint64_t rng_state = 0x6576616c2d766563ULL;

static uint64_t rnd(void) {
    uint64_t z = (rng_state += 0x9e3779b97f4a7c15ULL);
    z = (z ^ (z >> 30)) * 0xbf58476d1ce4e5b9ULL;
    z = (z ^ (z >> 27)) * 0x94d049bb133111ebULL;
    return z ^ (z >> 31);
}

static uint64_t rnd_below(uint64_t n) {
    return n ? rnd() % n : 0;
}

#define PICK(arr) ((arr)[rnd_below(COUNT(arr))])

// ------------------------------------------------------------------------------------------------
// variable bindings

struct binding {
    int set;
    char *name;
    double value;
};

static struct binding bindings[64];
static size_t bindings_count;

static void binding_add(int set, const char *name, double value) {
    if(bindings_count == COUNT(bindings)) {
        fprintf(stderr, "too many bindings\n");
        exit(1);
    }
    bindings[bindings_count++] = (struct binding){ .set = set, .name = strdupz(name), .value = value };
}

static char *repeated(char c, size_t n) {
    char *s = mallocz(n + 1);
    memset(s, c, n);
    s[n] = '\0';
    return s;
}

static void bindings_init(const char *dir) {
    binding_add(1, "a", 1);
    binding_add(1, "b", 2);
    binding_add(1, "c", 3);
    binding_add(1, "zero", 0);
    binding_add(1, "neg", -5.5);
    binding_add(1, "half", 0.5);
    binding_add(1, "big", 1e308);
    binding_add(1, "tiny", 5e-324);
    binding_add(1, "y", 4);
    binding_add(1, "xy", 6);
    // names only the lexer's rules explain
    binding_add(1, "a.b", 7);
    binding_add(1, "a:b", 8);
    binding_add(1, "b:$c", 9);
    binding_add(1, "a b", 10);
    binding_add(1, repeated('n', 298), 11);
    binding_add(1, repeated('n', 299), 12); // what a name of 300 bytes or more is cut to

    binding_add(2, "a", NAN);
    binding_add(2, "b", INFINITY);
    binding_add(2, "c", -INFINITY);
    binding_add(2, "zero", -0.0);
    binding_add(2, "neg", double_of(0xfff8000000000001ULL)); // a NaN with its sign bit and a payload

    FILE *f = out_open(dir, "bindings.tsv", "set, name, value bits");
    for(size_t i = 0; i < bindings_count; i++) {
        fprintf(f, "%d\t", bindings[i].set);
        esc_str(f, bindings[i].name);
        fprintf(f, "\t%016llx\n", (unsigned long long)bits_of(bindings[i].value));
    }
    fclose(f);
}

static bool lookup(STRING *variable, void *data, NETDATA_DOUBLE *result) {
    int set = (int)(intptr_t)data;
    const char *name = string2str(variable);
    for(size_t i = 0; i < bindings_count; i++) {
        if(bindings[i].set == set && strcmp(bindings[i].name, name) == 0) {
            *result = bindings[i].value;
            return true;
        }
    }
    return false;
}

// ------------------------------------------------------------------------------------------------
// rows

static FILE *corpus;
static FILE *hardcode;

static const char untouched_at = '\0'; // what *failed_at holds before the call
#define UNTOUCHED_ERROR (-12345)

static void eval_fields(FILE *f, EVAL_EXPRESSION *exp, int set) {
    expression_set_variable_lookup_callback(exp, set ? lookup : NULL, (void *)(intptr_t)set);
    int ret = expression_evaluate(exp);
    fprintf(f, "\t%d\t%d\t%016llx\t", ret, exp->error, (unsigned long long)bits_of(exp->result));
    esc_str(f, expression_error_msg(exp));
}

static void corpus_row(const char *family, const char *input) {
    fputs(family, corpus);
    fputc('\t', corpus);
    esc_str(corpus, input);

    const char *failed_at = &untouched_at;
    int error = UNTOUCHED_ERROR;
    EVAL_EXPRESSION *exp = expression_parse(input, &failed_at, &error);

    if(!exp) {
        if(error == UNTOUCHED_ERROR && failed_at == &untouched_at)
            fputs("\tE\t-\t-", corpus);
        else if(error == UNTOUCHED_ERROR || failed_at == &untouched_at || !failed_at) {
            fprintf(stderr, "half-reported parse failure for '%s'\n", input);
            exit(1);
        }
        else
            fprintf(corpus, "\tF\t%d\t%zu", error, (size_t)(failed_at - input));

        fputs("\t-\t-", corpus);
        for(int set = 0; set < 3; set++)
            fputs("\t-\t-\t-\t-", corpus);
    }
    else {
        if(failed_at) {
            fprintf(stderr, "a parsed expression reports a position for '%s'\n", input);
            exit(1);
        }
        fprintf(corpus, "\tK\t%d\t-\t", error);
        esc_str(corpus, expression_source(exp));
        fputc('\t', corpus);
        esc_str(corpus, expression_parsed_as(exp));
        for(int set = 0; set < 3; set++)
            eval_fields(corpus, exp, set);
        expression_free(exp);
    }

    fputc('\n', corpus);
}

static void corpus_rows(const char *family, const char *const *inputs, size_t count) {
    for(size_t i = 0; i < count; i++)
        corpus_row(family, inputs[i]);
}

// each value in each template
static void corpus_templates(const char *family, const char *const *templates, size_t templates_count,
                             const char *const *values, size_t values_count) {
    SB b = { 0 };
    for(size_t v = 0; v < values_count; v++)
        for(size_t t = 0; t < templates_count; t++)
            corpus_row(family, subst(&b, templates[t], values[v]));
    freez(b.s);
}

static void hardcode_one(EVAL_EXPRESSION *exp, const char *name, double value) {
    STRING *variable = string_strdupz(name);
    expression_hardcode_variable(exp, variable, value);
    string_freez(variable);
}

static void hardcode_row(const char *input, const char *name1, double value1, const char *name2, double value2) {
    const char *failed_at = NULL;
    int error = 0;
    EVAL_EXPRESSION *exp = expression_parse(input, &failed_at, &error);
    if(!exp) {
        fprintf(stderr, "hardcode input does not parse: '%s'\n", input);
        exit(1);
    }

    esc_str(hardcode, input);
    fprintf(hardcode, "\t%d\t", name2 ? 2 : 1);
    esc_str(hardcode, name1);
    fprintf(hardcode, "\t%016llx\t", (unsigned long long)bits_of(value1));
    hardcode_one(exp, name1, value1);
    if(name2) {
        esc_str(hardcode, name2);
        fprintf(hardcode, "\t%016llx\t", (unsigned long long)bits_of(value2));
        hardcode_one(exp, name2, value2);
    }
    else
        fputs("-\t-\t", hardcode);

    esc_str(hardcode, expression_source(exp));
    fputc('\t', hardcode);
    esc_str(hardcode, expression_parsed_as(exp));
    eval_fields(hardcode, exp, 1);
    fputc('\n', hardcode);
    expression_free(exp);
}

