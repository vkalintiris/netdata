// hardcode

static void family_hardcode(void) {
    static const char *const inputs[] = {
        "$x", "${x}", "$x + 1", "${x} + 1", "1 + $x", "$x + ${x}", "${x} + $x", "$x + $x + $x", "${x}*${x}", "$y + 1",
        "33 + 33", "$x + $xy", "$xy + $x", "${x} + ${xy}", "$xy + ${x}", "$xx + $xx + $x", "$x.a + $x", "$x + $x.a", "($x)",
        "-$x", "!$x", "abs($x)", "$x ? $x : $x", "$x > 5 ? $x : ${x}", "$x$x", "$x$x + $x", "$x-$x", "$x/$x", "$X + $x",
        "$x + $y", "${x } + $x", "$x + ${x} + $x + ${x}", "$xy + $xy + $x + $x", "$x  +  $x",
    };
    double values[] = {
        5, 42, -5.5, 0, -0.0, NAN, INFINITY, -INFINITY, 0.1234567, 123456789, 1e308, 1e-7, 5e-324, 1234567.1234567,
        -123456789012.0,
    };

    for(size_t i = 0; i < COUNT(inputs); i++)
        for(size_t v = 0; v < COUNT(values); v++)
            hardcode_row(inputs[i], "x", values[v], NULL, 0);

    static const struct {
        const char *input;
        const char *name1;
        const char *name2;
    } pairs[] = {
        { "$a + $x", "a", "x" },          { "$x + $y", "x", "y" },         { "$x + $y", "y", "x" },
        { "$x + $xy", "x", "xy" },        { "$x + $xy", "xy", "x" },       { "$x + $x", "x", "x" },
        { "$xx + $xx + $x", "x", "xx" },  { "$xx + $xx + $x", "xx", "x" }, { "${x} + $x", "x", "x" },
        { "$x + ${y} + $x", "y", "x" },   { "$y + $y", "x", "y" },         { "$x.a + $x", "x.a", "x" },
        { "$x.a + $x", "x", "x.a" },      { "${x y} + $x", "x y", "x" },   { "$x + 1", "", "x" },
    };
    double pair_values[][2] = { { 5, 7 }, { 123456789, 1 }, { 1, 123456789 }, { NAN, INFINITY }, { -1.5, 1e308 } };

    for(size_t i = 0; i < COUNT(pairs); i++)
        for(size_t v = 0; v < COUNT(pair_values); v++)
            hardcode_row(pairs[i].input, pairs[i].name1, pair_values[v][0], pairs[i].name2, pair_values[v][1]);

    // a stack reset frees the nodes parsed before it: their variables are in the text but no longer in the tree
    static const char *const after_reset[] = { "$x + 1 $x", "$x + 1 $x + $x", "$x + 1 ${x}", "$x + 1 $y" };
    SB b = { 0 };
    for(size_t i = 0; i < COUNT(after_reset); i++) {
        sb_reset(&b);
        sb_rep(&b, "(", 97);
        sb_add(&b, after_reset[i]);
        hardcode_row(b.s, "x", 5, NULL, 0);
        hardcode_row(b.s, "x", 123456789, NULL, 0);
    }
    freez(b.s);
}

